#!/usr/bin/env python3
import sys

# ตรวจสอบว่ามีพารามิเตอร์ส่งเข้ามา 1 ตัวพอดีหรือไม่ 
# (len(sys.argv) == 2 เพราะ index 0 คือชื่อไฟล์โปรแกรม ส่วน index 1 คือพารามิเตอร์ตัวแรก)
if len(sys.argv) == 2:
    # ถ้ารับพารามิเตอร์มา 1 ตัวพอดี ให้นำมาแปลงเป็นตัวพิมพ์ใหญ่ด้วย .upper() แล้วพิมพ์ออกมา
    print(sys.argv[1].upper())
else:
    # ถ้าจำนวนพารามิเตอร์ไม่เท่ากับ 1 (ไม่มีเลย หรือมีมากกว่า 1 ตัว) ให้พิมพ์ none
    print("none")