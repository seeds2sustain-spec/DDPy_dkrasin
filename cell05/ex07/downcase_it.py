#!/usr/bin/env python3
import sys

# ตรวจสอบว่ามีพารามิเตอร์ส่งเข้ามา 1 ตัวพอดีหรือไม่ (ความยาว argv ต้องเป็น 2)
if len(sys.argv) == 2:
    # นำพารามิเตอร์ตัวแรกมาแปลงเป็นตัวพิมพ์เล็กด้วย .lower() แล้วพิมพ์ออกมา
    print(sys.argv[1].lower())
else:
    # ถ้าจำนวนพารามิเตอร์ไม่เท่ากับ 1 ให้พิมพ์ none
    print("none")