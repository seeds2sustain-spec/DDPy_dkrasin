#!/usr/bin/env python3
import sys

# ตรวจสอบว่าความยาวของอาร์กิวเมนต์มากกว่า 1 หรือไม่ (มีพารามิเตอร์ต่อท้ายชื่อไฟล์หรือไม่)
if len(sys.argv) > 1:
    # ถ้ามี ให้พิมพ์พารามิเตอร์ตัวแรกสุดที่ส่งเข้ามา (ตัวที่ index 1)
    print(sys.argv[1])
else:
    # ถ้าไม่มีพารามิเตอร์เลย ให้พิมพ์คำว่า none
    print("none")