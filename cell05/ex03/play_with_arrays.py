#!/usr/bin/env python3

original_array = [2, 8, 9, 48, 8, 22, -12, 2]
new_array = []

# ใช้ range(len()) เพื่อสร้างลำดับตัวเลข 0 ถึง (จำนวนข้อมูล - 1)
for i in range(len(original_array)):
    # อ้างอิงข้อมูลด้วยตำแหน่ง [i] แล้วนำมาบวก 2
    new_array.append(original_array[i] + 2)

unique_array = set(new_array)

print(original_array)
print(unique_array)

# === สรุปขั้นตอนการทำงานแบบเข้าใจง่าย (Easy Steps) ===
#len(...): คือการ "นับจำนวน" ว่าในกลุ่มข้อมูลนั้นมีของอยู่กี่ชิ้น (เช่น ถ้ามีของ 5 ชิ้น len จะได้ค่าเป็น 5)

#range(...): คือการ "สร้างลำดับตัวเลข" โดยจะเริ่มจาก 0 เสมอ (เช่น range(5) จะสร้างเลข 0, 1, 2, 3, 4)

# 1. เตรียมข้อมูล
# - original_array: เก็บชุดตัวเลขตั้งต้น
# - new_array: สร้างลิสต์ว่างๆ ไว้รอเก็บผลลัพธ์
# - i = 0: ตัวนับตำแหน่ง เริ่มจาก 0 (ตำแหน่งแรกสุด)

# 2. วนลูปทำงาน (Loop)
# - while สั่งให้ทำซ้ำไปเรื่อยๆ ตราบใดที่ยังดึงตัวเลขไม่ครบทุกตัว (i น้อยกว่าจำนวนข้อมูลทั้งหมด)
# - ดึงเลขตำแหน่งที่ i มาบวก 2 แล้วจับใส่ใน new_array
# - เพิ่มค่า i ขึ้น 1 เพื่อขยับไปทำตัวถัดไป

# 3. กำจัดตัวซ้ำและแสดงผล
# - ใช้ set() คัดกรอง new_array ให้เหลือแค่ตัวเลขที่ไม่ซ้ำกัน
# - พิมพ์ผลลัพธ์ตัวเลขชุดเก่า และตัวเลขชุดใหม่ออกมาดู